//! A test fixture: a small INI grammar of our own, built as a native
//! grammar library, the shape a grammar loaded at run time has (a shared
//! library exporting `tree_sitter_<name>`).
//!
//! The syntax adapter's tests load it (`editor-syntax-treesitter`'s
//! `tests/registration.rs` and `tests/contract.rs`), and so does
//! `editor-ffi`'s wiring test of a registration through C
//! (`tests/grammars.rs`); `mise run ffi-test` hands its path, printed by
//! this crate's binary, to Lean's `contract-test`. Later phases of the
//! roadmap `syntax-runtime-grammars` reuse it. Each user reaches it by a
//! dev-dependency, and the editor never links it (`deny.toml`).
//!
//! **The grammar.** `grammar/grammar.js` is ours: sections `[name]`,
//! `key = value` pairs and `;` or `#` comments. Its name, `ini`, is not one
//! of the grammars compiled into the adapter. Its parser,
//! `grammar/src/`, is generated by the tree-sitter CLI, checked in and never
//! edited (`README.md` gives the CLI's version and the command).
//!
//! **Why a build-script product, not a `cdylib`.** The library is compiled
//! and linked by `build.rs` into `OUT_DIR`, and its path is [`LIBRARY`]. A
//! Cargo `cdylib` would not do: on stable Cargo its path cannot reach
//! another crate's tests (artifact dependencies are unstable), it lands in
//! `target/*/deps/` under a hashed name and is not built when only a
//! dependent crate is tested, and a Rust `cdylib` does not export the C
//! symbols of a static archive linked into it.
//!
//! **Its queries beside it.** The build script also copies
//! `grammar/queries/highlights.scm` to `queries/highlights.scm` in the
//! library's own directory, the layout a grammar declaration's default query
//! directory reads (`<library dir>/queries/`), so Lean's wiring check
//! declares the fixture by its name and path alone.
//!
//! **Its exports**, each a fixture for one property, not a grammar to use:
//! [`SYMBOL`], the grammar; [`OVERRIDING_SYMBOL`], the same grammar under a
//! compiled-in name; and [`ABI_0_SYMBOL`], a language of ABI 0.

/// The built library's absolute path. Its directory holds
/// `queries/highlights.scm`, a copy of [`HIGHLIGHTS`].
pub const LIBRARY: &str = env!("EDITOR_SYNTAX_FIXTURE_INI_LIBRARY");

/// The grammar's name.
pub const NAME: &str = "ini";

/// The symbol that exports the grammar.
pub const SYMBOL: &str = "tree_sitter_ini";

/// A symbol that exports the same grammar under the name of a grammar
/// compiled into the adapter, `json`: a library that overrides it.
pub const OVERRIDING_SYMBOL: &str = "tree_sitter_json";

/// A symbol that exports a language of ABI 0, below any version the
/// parsing library accepts; every other field of it is zero.
pub const ABI_0_SYMBOL: &str = "tree_sitter_abi_0";

/// A file that exists and is no library: the grammar's source.
pub const NOT_A_LIBRARY: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/grammar/grammar.js");

/// The highlights query that sits beside the grammar's library.
pub const HIGHLIGHTS: &str = include_str!("../grammar/queries/highlights.scm");

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn the_highlights_query_sits_in_the_queries_directory_beside_the_library() {
        let path = Path::new(LIBRARY)
            .parent()
            .expect("the library has a directory")
            .join("queries")
            .join("highlights.scm");
        #[expect(
            clippy::disallowed_methods,
            reason = "the test reads the query the build script wrote beside the library, the layout a declaration's default query directory reads"
        )]
        let read = std::fs::read_to_string(&path);
        let query = read.unwrap_or_else(|error| panic!("reading {}: {error}", path.display()));
        assert_eq!(query, HIGHLIGHTS);
    }
}
